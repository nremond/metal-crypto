#!/usr/bin/env python3
"""Emit aes_tables.h with AES S-box and encryption T-tables Te0..Te3.
Usable from both C (ref.c) and Metal (crypto.metal)."""
import os

def gmul(a, b):
    r = 0
    for _ in range(8):
        if b & 1: r ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi: a ^= 0x1B
        b >>= 1
    return r

# sbox via inverse in GF(2^8) + affine transform
def ginv(a):
    if a == 0: return 0
    return gmul(a, 1) and pow(a, 254, 256) if False else _inv(a)
def _inv(a):
    # a^254 in GF(2^8)
    r, base, e = 1, a, 254
    while e:
        if e & 1: r = gmul(r, base)
        base = gmul(base, base); e >>= 1
    return r

sbox = [0] * 256
for x in range(256):
    i = _inv(x)
    sbox[x] = i ^ ((i << 1) | (i >> 7)) ^ ((i << 2) | (i >> 6)) ^ ((i << 3) | (i >> 5)) ^ ((i << 4) | (i >> 4)) ^ 0x63
    sbox[x] &= 0xFF
assert sbox[0x00] == 0x63 and sbox[0x53] == 0xED and sbox[0xFF] == 0x16

def rotl8(x, n): return ((x << n) | (x >> (8 - n))) & 0xFF
Te0 = [gmul(sbox[x], 2) << 24 | sbox[x] << 16 | sbox[x] << 8 | gmul(sbox[x], 3) for x in range(256)]
Te1 = [rotl8(t, 1) << 24 | (t >> 8) & 0xFF00 | (t >> 16) & 0xFF | rotl8(t >> 24, 1) for t in Te0]
# simpler: Te_{i} = rotate right Te0 by 8*i bits
def ror32(x, n): return ((x >> n) | (x << (32 - n))) & 0xFFFFFFFF
Te1 = [ror32(t, 8) for t in Te0]
Te2 = [ror32(t, 16) for t in Te0]
Te3 = [ror32(t, 24) for t in Te0]

def fmt(name, arr, ty, hexf):
    rows = []
    for i in range(0, 256, 8):
        rows.append("    " + ",".join(hexf % v for v in arr[i:i+8]) + ",")
    return "%s %s[256] = {\n%s\n};\n" % (ty, name, "\n".join(rows))

hdr = ["/* Auto-generated by gen_aes_tables.py. Do not edit. */", "#pragma once", ""]
body_c = [fmt("sbox", sbox, "static const unsigned char", "0x%02x"),
          fmt("Te0", Te0, "static const unsigned int", "0x%08xu"),
          fmt("Te1", Te1, "static const unsigned int", "0x%08xu"),
          fmt("Te2", Te2, "static const unsigned int", "0x%08xu"),
          fmt("Te3", Te3, "static const unsigned int", "0x%08xu")]
body_m = [fmt("sbox", sbox, "constant uchar", "0x%02xu"),
          fmt("Te0", Te0, "constant uint", "0x%08xu"),
          fmt("Te1", Te1, "constant uint", "0x%08xu"),
          fmt("Te2", Te2, "constant uint", "0x%08xu"),
          fmt("Te3", Te3, "constant uint", "0x%08xu")]
hdr.append("#ifdef __METAL_VERSION__")
hdr += body_m
hdr.append("#else")
hdr += body_c
hdr.append("#endif")
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "aes_tables.h"), "w") as f:
    f.write("\n".join(hdr) + "\n")
print("aes_tables.h written")
