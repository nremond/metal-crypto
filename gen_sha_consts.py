#!/usr/bin/env python3
"""Emit sha_consts.h with SHA-256 K table / SHA-512 K table / IVs, computed from
fractional parts of cube (256) and square (512) roots of the first primes.
Valid C and valid Metal (uint / ulong literals)."""
import os
from decimal import Decimal, getcontext

getcontext().prec = 120

def primes(n):
    ps, c = [], 2
    while len(ps) < n:
        if all(c % p for p in ps if p * p <= c):
            ps.append(c)
        c += 1
    return ps

def frac_const(root, prime, bits):
    # integer part of fractional bits: floor(frac(p^(1/root)) * 2^bits)
    x = Decimal(prime) ** (Decimal(1) / Decimal(root))
    frac = x - int(x)
    return int(frac * (1 << bits))

K256 = [frac_const(3, p, 32) for p in primes(64)]
K512 = [frac_const(3, p, 64) for p in primes(80)]
IV256 = [frac_const(2, p, 32) for p in primes(8)]
IV512 = [frac_const(2, p, 64) for p in primes(8)]

# sanity against well-known values
assert K256[0] == 0x428a2f98 and K256[63] == 0xc67178f2
assert IV256[0] == 0x6a09e667 and IV256[7] == 0x5be0cd19
assert K512[0] == 0x428a2f98d728ae22 and K512[79] == 0x6c44198c4a475817
assert IV512[0] == 0x6a09e667f3bcc908 and IV512[7] == 0x5be0cd19137e2179

def block(name, arr, bits):
    lit = "u" if bits == 32 else "UL"
    rows = []
    step = 8 if bits == 32 else 4
    for i in range(0, len(arr), step):
        rows.append("    " + ",".join("0x%0*x%s" % (bits // 4, v, lit) for v in arr[i:i+step]) + ",")
    return "static const %s %s[%d] = {\n%s\n};\n" % (
        "unsigned" if bits == 32 else "unsigned long long", name, len(arr), "\n".join(rows))

def block_m(name, arr, bits):
    lit = "" if bits == 32 else "UL"
    rows = []
    step = 8 if bits == 32 else 4
    for i in range(0, len(arr), step):
        rows.append("    " + ",".join("0x%0*x%s" % (bits // 4, v, lit) for v in arr[i:i+step]) + ",")
    return "constant %s %s[%d] = {\n%s\n};\n" % (
        "uint" if bits == 32 else "ulong", name, len(arr), "\n".join(rows))

out = ["/* Auto-generated by gen_sha_consts.py. Do not edit. */", "#pragma once", "",
       "#ifdef __METAL_VERSION__"]
out += [block_m("SHA256_K", K256, 32), block_m("SHA256_H", IV256, 32),
        block_m("SHA512_K", K512, 64), block_m("SHA512_H", IV512, 64)]
out.append("#else")
out += [block("SHA256_K", K256, 32), block("SHA256_H", IV256, 32),
        block("SHA512_K", K512, 64), block("SHA512_H", IV512, 64)]
out.append("#endif")
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "sha_consts.h"), "w") as f:
    f.write("\n".join(out) + "\n")
print("sha_consts.h written")
